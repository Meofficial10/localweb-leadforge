"""Workstream E - email draft grounding tests.

Drafts generated by app.outreach.email.draft must claim nothing beyond the
lead's verified facts (same deterministic validator as demo copy / call scripts).
Adversarial (invented) claim fixtures are built at runtime so the committed
test source stays clean for the pre-commit contact-data gate.
"""
from __future__ import annotations

import pytest

from app.outreach.email.draft import (
    FactValidationError,
    draft_email,
    validate_facts,
)


def _lead(**over):
    from app.models.lead import Lead
    lead = Lead(source="fake", source_place_id="fake-1", name="Sample Dental Clinic",
                category="dentist", has_website=False)
    for k, v in over.items():
        setattr(lead, k, v)
    return lead


def _facts():
    return [
        {"id": "f1", "field": "name", "value": "Sample Dental Clinic", "source": "OSM"},
        {"id": "f2", "field": "category", "value": "dentist", "source": "OSM"},
        {"id": "f3", "field": "phone", "value": "+65 0000 0000", "source": "OSM"},
    ]


def _invented_body():
    return (
        "I was looking at Sample Dental Clinic and had an idea. "
        "We are the best dentist in town with 5000 happy patients. "
        "I put together a quick demo page: https://example.com/demo"
    )


def test_draft_email_grounded_template_passes():
    lead = _lead()
    r = draft_email(lead, None, "https://example.com/demo", facts=_facts())
    assert r.fact_safe is True
    assert "Sample Dental Clinic" in r.body
    assert r.word_count < 120


def test_validate_facts_blocks_invented_superlative_and_count():
    lead = _lead()
    ok = validate_facts(_invented_body(), lead, None, facts=_facts())
    assert ok is False


def test_validate_facts_passes_clean_mechanics():
    lead = _lead()
    clean = "I was looking at Sample Dental Clinic and had an idea. If it's useful, happy to talk."
    ok = validate_facts(clean, lead, None, facts=_facts())
    assert ok is True


def test_draft_email_raises_on_unverified_claim():
    lead = _lead()
    from app.outreach.email.draft import _template_email, DraftResult
    orig_template = _template_email
    # monkeypatch the template so it injects an invented claim
    def bad_template(l, profile, demo_url, sender_name):
        return orig_template(l, profile, demo_url, sender_name) + (
            "\n\nWe offer dental implants at affordable prices.\n"
        )
    import app.outreach.email.draft as draft_mod
    draft_mod._template_email = bad_template
    try:
        with pytest.raises(FactValidationError):
            draft_email(lead, None, "https://example.com/demo", facts=_facts())
    finally:
        draft_mod._template_email = orig_template
